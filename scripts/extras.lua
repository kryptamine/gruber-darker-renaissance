-- Writes every file in extras/ from the palette, with the default options.
-- Run from the repository root: nvim --headless -u NONE -l scripts/extras.lua
vim.opt.rtp:prepend(vim.fn.getcwd())

local colors = require("gruber-darker-renaissance.colors")
local config = require("gruber-darker-renaissance.config")
local terminal = require("gruber-darker-renaissance.terminal")

local c = colors.setup(vim.deepcopy(config.defaults))
local ansi = terminal.ansi(c)

local header = "# Generated by `make extras` from palette.lua. Do not edit by hand.\n\n"

for _, name in ipairs({ "alacritty", "fish", "foot", "ghostty", "herdr", "kitty", "lazygit" }) do
	local extra = require("gruber-darker-renaissance.extras." .. name)
	local path = "extras/" .. extra.path
	vim.fn.mkdir(vim.fs.dirname(path), "p")
	local file = assert(io.open(path, "w"))
	file:write(header, extra.render(c, ansi), "\n")
	file:close()
end

print("ok")
